import fs from 'fs';
import path from 'path';
import type { TestRunSummary, TestResultFinding } from './runner';
import { VcsFactory } from '../../services/vcs/VcsFactory';
import { readCiPrContext } from '../../services/ciContext';
import crypto from 'crypto';

const sha1 = (s: string): string => crypto.createHash('sha1').update(s).digest('hex');

const fingerprintFinding = (f: TestResultFinding): string =>
  sha1(`${f.testFilePath}|${f.suite || ''}|${f.testName}|${f.framework}|${f.outcome}`).slice(0, 12);

const MANAGED_TITLE_MATCH = /^\[TEST\]/;

const perFindingTitle = (f: TestResultFinding): string => {
  const eco = {
    jest: '🟩 JEST', vitest: '🟩 VITEST', mocha: '🟩 MOCHA', pytest: '🐍 PYTEST', unittest: '🐍 UNITTEST',
    go: '🐹 GO', cargo: '🦀 CARGO', rspec: '💎 RSPEC', junit: '☕ JUNIT', phpunit: '🐘 PHPUNIT',
    dotnet: '🔷 DOTNET', c: '⚙️  C'
  } as Record<string, string>;
  const badge = eco[f.framework] || f.framework.toUpperCase();
  const outcomeBadge = f.outcome === 'passed' ? '✅' : f.outcome === 'failed' ? '❌' : f.outcome === 'skipped' ? '⏭️' : f.outcome === 'error' ? '💥' : '⚪';
  return `[TEST]${outcomeBadge}[${badge}] ${path.basename(f.testFilePath)} · ${(f.suite ? `${f.suite} · ` : '')}${f.testName} (fp${fingerprintFinding(f).slice(0, 10)})`;
};

const perFindingBody = (f: TestResultFinding, headerSummaryMarkdown: string): string => {
  const lines: string[] = [];
  lines.push('### Orchestra test-gen: managed test finding');
  lines.push('');
  lines.push(headerSummaryMarkdown);
  lines.push('');
  lines.push('#### Test case detail');
  lines.push(`- **Framework:** \`${f.framework}\``);
  lines.push(`- **Language:** \`${f.language}\``);
  lines.push(`- **Test file:** \`${f.testFilePath}\``);
  if (f.suite) lines.push(`- **Suite:** \`${f.suite}\``);
  lines.push(`- **Test name:** \`${f.testName}\``);
  lines.push(`- **Fully qualified:** \`${f.fullyQualifiedName}\``);
  lines.push(`- **Outcome:** **${f.outcome.toUpperCase()}**${f.durationMs ? ` · ${f.durationMs}ms` : ''}`);
  lines.push(`- **Generated by test-gen:** ${f.generatedByTestGen ? '✅ yes' : '➖ existing test suite'}`);
  lines.push(`- **Fingerprint:** \`${fingerprintFinding(f)}\``);
  lines.push('');
  if (f.outcome === 'failed' || f.outcome === 'error' || f.outcome === 'timeout') {
    lines.push('#### Failure detail');
    if (f.failureMessage) lines.push(f.failureMessage);
    if (f.failureStack) lines.push(`\n\`\`\`\n${f.failureStack}\n\`\`\`\n`);
    lines.push('');
    lines.push('> Fix guidance: re-run `orchestra test-gen <source file>` to regenerate/expand the test, or run `orchestra vuln-scan` if the failure is security-related.');
  } else {
    lines.push('✅ Test outcome: passing / skipped. No failure detail recorded.');
  }
  return lines.join('\n');
};

export const buildMarkdownReport = (summary: TestRunSummary): string => {
  const lines: string[] = [];
  lines.push('# Orchestra Test Report');
  lines.push('');
  lines.push(`- **Generated at:** ${summary.generatedAt}`);
  lines.push(`- **Target:** ${summary.target || summary.repoRoot}`);
  lines.push(`- **Framework auto-detected:** \`${summary.framework}\` (confidence ${Math.round(summary.frameworkConfidence * 100)}%)`);
  lines.push(`- **Evidence:** ${summary.evidence.join('; ') || '—'}`);
  lines.push(`- **Total duration:** ${(summary.totalDurationMs / 1000).toFixed(2)}s`);
  lines.push('');
  lines.push('## Summary counts');
  lines.push('');
  lines.push('| Metric | Count |');
  lines.push('|---|---:|');
  lines.push(`| Tests generated by \`test-gen\` AI | ${summary.testsGenerated} |`);
  lines.push(`| Tests discovered (parsed from runner output) | ${summary.testsDiscovered} |`);
  lines.push(`| ✅ Passed | ${summary.testsPassed} |`);
  lines.push(`| ❌ Failed | ${summary.testsFailed} |`);
  lines.push(`| 💥 Errored / Timeout | ${summary.testsErrored} |`);
  lines.push(`| ⏭️ Skipped | ${summary.testsSkipped} |`);
  lines.push(`| ⚪ Unknown | ${summary.unknown} |`);
  lines.push('');
  if (summary.invocations.length > 0) {
    lines.push('## Runner invocations');
    lines.push('');
    lines.push('| # | Binary | Args | Exit code | Duration (ms) | Stdout head | Stderr head |');
    lines.push('|---:|---|---|---:|---:|---|---|');
    for (let i = 0; i < summary.invocations.length; i++) {
      const inv = summary.invocations[i];
      lines.push(`| ${i + 1} | \`${inv.command.replace(/\|/g, '\\|')}\` | \`${inv.args.join(' ').replace(/\|/g, '\\|')}\` | ${inv.exitCode === null ? 'n/a' : inv.exitCode} | ${inv.durationMs} | ${headCol(inv.stdoutHead)} | ${headCol(inv.stderrHead)} |`);
    }
    lines.push('');
  }
  if (summary.errors.length > 0) {
    lines.push('## Errors');
    lines.push('');
    for (const e of summary.errors) lines.push(`- ${e}`);
    lines.push('');
  }
  lines.push('## Findings (top 100 by failing-first then test file)');
  lines.push('');
  lines.push('| # | Outcome | Framework | Test file | Suite / Test | Duration | Fingerprint |');
  lines.push('|---:|---|---|---|---|---:|---|');
  const findings = [...summary.findings].sort((a, b) => {
    const rank = (o: string) => o === 'failed' ? 0 : o === 'error' || o === 'timeout' ? 1 : o === 'unknown' ? 2 : o === 'skipped' ? 3 : 4;
    return rank(a.outcome) - rank(b.outcome) || a.testFilePath.localeCompare(b.testFilePath) || a.fullyQualifiedName.localeCompare(b.fullyQualifiedName);
  });
  for (let i = 0; i < Math.min(findings.length, 100); i++) {
    const f = findings[i];
    const outcomeBadge = f.outcome === 'passed' ? '✅' : f.outcome === 'failed' ? '❌' : f.outcome === 'skipped' ? '⏭️' : f.outcome === 'error' || f.outcome === 'timeout' ? '💥' : '⚪';
    const qualified = f.suite ? `**${f.suite}** › ${f.testName}` : f.testName;
    lines.push(`| ${i + 1} | ${outcomeBadge} ${f.outcome} | \`${f.framework}\` | \`${f.testFilePath.replace(/\|/g, '\\|')}\` | ${qualified.replace(/\|/g, '\\|')} | ${f.durationMs ?? '—'} | \`${fingerprintFinding(f).slice(0, 10)}\` |`);
  }
  if (findings.length > 100) lines.push(`\n_Showing first 100 of ${findings.length} findings. Full list in \`.orchestra/test-results.json\`._\n`);
  return lines.join('\n');
};

const headCol = (s: string) => s ? `\`${s.replace(/`/g, "'").replace(/\|/g, '\\|').replace(/\n/g, ' ').slice(0, 120)}\`` : '';

const headerSummaryMarkdown = (summary: TestRunSummary): string => {
  return `**Scan summary:** framework \`${summary.framework}\` · discovered ${summary.testsDiscovered} · ✅ ${summary.testsPassed} · ❌ ${summary.testsFailed} · 💥 ${summary.testsErrored} · ⏭️ ${summary.testsSkipped} · ⚪ ${summary.unknown} in ${(summary.totalDurationMs / 1000).toFixed(2)}s.`;
};

export const handleReportOutput = async (params: {
  dirPath: string;
  mode: string;
  report: string;
  hasIssues: boolean;
  reportFileName: string;
  issueTitle?: string;
  issueLabels?: string[];
  prCommentHeader?: string;
  successMessage?: string;
  findings?: TestResultFinding[];
  summary?: TestRunSummary;
}): Promise<void> => {
  const { dirPath, mode, report, hasIssues, reportFileName } = params;
  const reportPath = path.join(dirPath, reportFileName);
  fs.mkdirSync(path.dirname(reportPath) || dirPath, { recursive: true });
  fs.writeFileSync(reportPath, report);
  console.log(`\n✅ ${params.successMessage || 'Test report'} written to ${reportPath}`);

  if (mode === 'report') return;

  const findings = params.findings || [];
  const summary = params.summary;
  const labels = params.issueLabels || ['orchestra', 'auto-scan', 'test-gen'];
  const prCommentHeader = params.prCommentHeader || '### 🧪 Orchestra Test Report\n';

  const vcs = VcsFactory.getProvider();
  const prContext = readCiPrContext();

  if (mode === 'issue') {
    const title = params.issueTitle || `Orchestra Test Report — ${summary ? `${summary.framework} ${summary.testsFailed || 0}/${summary.testsDiscovered || 0} failing` : ''}`;
    const existing = await vcs.findIssueByTitle(title);
    if (existing) {
      console.log(`ℹ️  Summary issue already exists (#${existing}). Appending report as comment instead.`);
      await vcs.addComment(existing, `${prCommentHeader}\n${summary ? headerSummaryMarkdown(summary) + '\n' : ''}\n${truncateMarkdown(report)}`);
    } else {
      const url = await vcs.createIssue(title, report, [...labels, 'test']);
      console.log(`✅ Summary issue created: ${url}`);
    }
    if (findings.length > 0) {
      console.log(`🧪 Also creating ${Math.min(findings.length, 200)} per-test VCS issues...`);
      await reconcilePerFindingIssues(dirPath, findings, summary || null, labels);
    }
    return;
  }

  if (mode === 'issues-per-test') {
    await reconcilePerFindingIssues(dirPath, findings, summary || null, labels);
    return;
  }

  if (mode === 'comment') {
    if (prContext && typeof prContext.prNumber === 'number') {
      console.log(`Commenting on PR #${prContext.prNumber}...`);
      await vcs.addComment(prContext.prNumber, `${prCommentHeader}\n${summary ? headerSummaryMarkdown(summary) + '\n' : ''}\n${truncateMarkdown(report)}`);
      console.log('✅ PR comment posted.');
    } else {
      console.log('ℹ️  No PR CI context for comment mode; wrote report to disk only.');
    }
    return;
  }

  console.log(`ℹ️  Unknown mode "${mode}"; fell back to report-only.`);
};

const truncateMarkdown = (md: string, maxChars = 6000): string => {
  if (md.length <= maxChars) return md;
  return `${md.slice(0, maxChars)}\n\n… _truncated ${md.length - maxChars} chars. See \`TEST_REPORT.md\` in the repo root for the complete output._\n`;
};

const reconcilePerFindingIssues = async (dirPath: string, findings: TestResultFinding[], summary: TestRunSummary | null, baseLabels: string[]): Promise<void> => {
  void dirPath;
  const vcs = VcsFactory.getProvider();
  const summaryMd = summary ? headerSummaryMarkdown(summary) : '';
  const wantTitles = new Map<string, TestResultFinding>();
  for (const f of findings) wantTitles.set(perFindingTitle(f), f);
  const openIssues: Array<{ id: number | string; title: string }> = [];
  try {
    const list = await vcs.listIssues('open');
    for (const it of list) if (MANAGED_TITLE_MATCH.test(it.title || '')) openIssues.push({ id: it.id, title: it.title || '' });
  } catch (err) {
    console.log(`⚠️  Could not list open issues (${err instanceof Error ? err.message : String(err)}); skipping per-test reconcile.`);
    return;
  }
  let created = 0; let commented = 0; let closed = 0;
  const alreadyOpen = new Map<string, number | string>();
  for (const it of openIssues) alreadyOpen.set(it.title, it.id);
  for (const [title, f] of wantTitles) {
    const extraLabels = [
      `test:${f.framework}`,
      `test:${f.language}`,
      `test:${f.outcome}`,
      f.generatedByTestGen ? 'test:generated' : 'test:existing'
    ];
    const labels = Array.from(new Set([...baseLabels, ...extraLabels]));
    const existingId = alreadyOpen.get(title);
    if (existingId !== undefined) {
      await vcs.addComment(existingId, `### 🧪 Orchestra: ${f.outcome.toUpperCase()} re-scanned\n\n${summaryMd}\n\n${perFindingBody(f, summaryMd)}`);
      commented += 1;
    } else {
      const url = await vcs.createIssue(title, perFindingBody(f, summaryMd), labels);
      if (url) created += 1;
    }
  }
  for (const it of openIssues) {
    if (wantTitles.has(it.title)) continue;
    try {
      await vcs.closeIssue(it.id, 'orchestra test-gen: this managed test finding is no longer present in the latest run.');
      closed += 1;
    } catch {}
  }
  console.log(`🧪 Per-test reconcile complete: created=${created} commented=${commented} closed=${closed}`);
};
